export async function checkNavigation(page, expect, audit = async () => undefined) {
  const area = page.getByRole("region", { name: "Поиск и навигация", exact: true });
  const combo = area.getByRole("button", { name: "Поиск категории", exact: true });
  await combo.click();
  await audit();
  let search = page.getByRole("combobox", { name: "Поиск вариантов", exact: true });
  await search.press("End");
  await expect(page.getByRole("option", { name: "Категория 250", exact: true })).toBeVisible();
  const mountedOptions = await page.getByRole("option").count();
  if (mountedOptions > 40) throw new Error(`Virtualized combobox mounted ${mountedOptions} options`);
  await search.press("Enter");
  await expect(combo).toHaveText("Категория 250");
  await expect(combo).toBeFocused();
  await combo.click();
  search = page.getByRole("combobox", { name: "Поиск вариантов", exact: true });
  await search.fill("Категория 004");
  await search.press("Enter");
  await expect(combo).toHaveText("Категория 004");
  await area.getByRole("button", { name: "Несколько категорий", exact: true }).click();
  await page.getByRole("option", { name: /Категория 001/ }).click();
  await page.getByRole("option", { name: /Категория 002/ }).click();
  await page.keyboard.press("Escape");
  await expect(area.getByTestId("multi-result")).toHaveText("Выбраны категории: 1, 2");
  const range = area.getByRole("button", { name: "Период операций", exact: true });
  await range.click();
  await audit();
  await page.getByRole("button", { name: "30 дней", exact: true }).click();
  await expect(range).toHaveText("25.09.2026 — 24.10.2026");
  await expect(range).toBeFocused();
  await area.getByRole("button", { name: "Действия", exact: true }).click();
  await page.getByRole("menuitem", { name: "Скопировать", exact: true }).click();
  await expect(area.getByRole("status", { name: "Результат действия" })).toHaveText("Скопировано");
  const context = area.getByRole("button", { name: "Контекстное меню", exact: true });
  await context.focus();
  await context.press("Shift+F10");
  await expect(page.getByRole("menu", { name: "Контекстные действия" })).toBeVisible();
  await page.keyboard.press("Escape");
  const tooltip = area.getByRole("button", { name: "Подсказка", exact: true });
  await tooltip.focus();
  await expect(page.getByRole("tooltip")).toBeVisible();
  await page.keyboard.press("Escape");
  const sheetTrigger = area.getByRole("button", { name: "Открыть шторку" });
  await sheetTrigger.click();
  await expect(page.getByRole("dialog", { name: "Настройки таблицы" })).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(sheetTrigger).toBeFocused();
  const confirmTrigger = area.getByRole("button", { name: "Подтверждение", exact: true });
  await confirmTrigger.click();
  const alert = page.getByRole("alertdialog");
  await expect(alert).toBeVisible();
  await expect(alert.getByRole("button", { name: "Отмена", exact: true })).toBeFocused();
  await audit();
  await alert.getByRole("button", { name: "Отмена", exact: true }).click();
  await expect(confirmTrigger).toBeFocused();
  await page.keyboard.press("Control+k");
  const palette = page.getByRole("dialog", { name: "Быстрые действия" });
  await expect(palette).toBeVisible();
  await audit();
  await palette.getByRole("combobox").fill("Перейти");
  await page.keyboard.press("Enter");
  await expect(area.getByRole("status", { name: "Результат действия" })).toHaveText("Таблица выбрана");
  const table = area.getByRole("table", { name: "Обычная таблица", exact: true });
  await table.getByRole("button", { name: "Название" }).click();
  await expect(table.getByRole("columnheader", { name: "Название" })).toHaveAttribute("aria-sort", "ascending");
  await table.getByRole("checkbox", { name: "Выбрать строку 1", exact: true }).click();
  await expect(area.getByTestId("selection-result")).toHaveText("Выбрано строк: 1");
  const virtual = area.getByRole("region", { name: "Виртуальная таблица", exact: true });
  await virtual.scrollIntoViewIfNeeded();
  await virtual.evaluate((element) => { element.scrollTop = element.scrollHeight; });
  await expect(virtual.getByRole("cell", { name: "Операция 500", exact: true })).toBeVisible();
  const rows = await virtual.getByRole("row").count();
  if (rows > 50) throw new Error(`Virtualized table mounted ${rows} rows`);
}
